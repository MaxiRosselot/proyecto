import { chromium, expect } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const base=process.env.LOCAL_PUBLIC_URL || 'http://127.0.0.1:5176';
if (!['127.0.0.1','localhost'].includes(new URL(base).hostname)) throw new Error('This test writes only to the local mock backend');
const evidence=path.resolve('docs/evidence/2026-09-21-refinements');
mkdirSync(evidence,{recursive:true});mkdirSync('output',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
try {
  const page=await browser.newPage({viewport:{width:1600,height:1100}});
  const errors=[];page.on('pageerror',e=>errors.push(e.stack || e.message));
  await page.goto(base+'/admin');
  await page.locator('input[type=password]').fill('2003');
  await page.getByRole('button',{name:'Ingresar'}).click();
  await page.getByRole('navigation').getByRole('button',{name:'Cotizar',exact:true}).click();
  await page.getByRole('button',{name:'Ingreso manual'}).click();
  await page.getByPlaceholder('Nombre completo').fill('CLIENTE DE PRUEBA');
  await page.getByPlaceholder('correo@ejemplo.com').fill('cliente@example.com');
  await page.getByPlaceholder('Direccion',{exact:true}).fill('Dirección de ejemplo');
  const priceRow=page.locator('table tbody tr').first();
  await priceRow.locator('input').last().fill('120000');
  page.once('dialog',dialog=>dialog.accept());
  await priceRow.getByRole('button',{name:'Actualizar valor en tabla'}).click();
  await expect(page.getByRole('status')).toContainText('guardado y verificado');
  const persisted=await page.request.get(base+'/.netlify/functions/get-precios',{headers:{'x-admin-password':'2003'}});
  const priceTable=(await persisted.json()).tabla;
  expect(priceTable.find(r=>r.alto===200 && r.prof===40 && r.desde===194).precio).toBe(120000);
  await page.screenshot({path:path.join(evidence,'01-actualizar-precio.png'),fullPage:true});
  await page.getByRole('button',{name:'Pantalla completa'}).click();
  const f=page.frameLocator('iframe[title="Configurador Repisas 3D"]');
  const field=label=>f.locator('.room-dimensions-section').getByLabel(label,{exact:true});
  await expect(field('Ancho puerta (cm)')).toHaveValue('80');
  await field('Muro A').fill('300');await field('Muro A').press('Enter');
  await f.getByLabel('Desplazar puerta',{exact:true}).press('Home');
  await expect(field('Muro D')).toHaveValue('0');await expect(field('Muro C')).toHaveValue('220');
  await f.getByLabel('Desplazar puerta',{exact:true}).press('End');
  await expect(field('Muro D')).toHaveValue('220');await expect(field('Muro C')).toHaveValue('0');
  await field('Alto bodega (cm)').fill('287');await field('Alto bodega (cm)').press('Enter');
  await expect(field('Alto bodega (cm)')).toHaveValue('287');
  await page.screenshot({path:path.join(evidence,'02-configuracion-recinto.png')});

  const project={projectName:'Bodega de prueba',units:'cm',room:{backWallCm:300,leftWallCm:240,rightWallCm:240,heightCm:287,door:{wall:'front',fromLeftCornerCm:110,toRightCornerCm:110,widthCm:80}},shelving:{layout:'manual',heightCm:200,depthCm:48,runs:[{id:'A',wall:'back',startCm:0,lengthCm:240,heightCm:200,depthCm:48},{id:'B',wall:'right',startCm:48,lengthCm:190,heightCm:200,depthCm:38,variants:[{type:'remove-lower-levels',count:2},{type:'hanging-rod',fromCm:0,toCm:190,heightCm:120}]}]}};
  // Exercise the supported load-project boundary, as when reopening a saved design.
  await page.evaluate(project=>document.querySelector('iframe[title="Configurador Repisas 3D"]').contentWindow.postMessage({type:'repisas:load-project',version:'1',requestId:'test-fixture',payload:{project}},location.origin),project);
  await f.getByRole('button',{name:'Plano 2D',exact:true}).click();
  await f.getByRole('button',{name:'Seleccionar',exact:true}).click();
  await f.locator('.editor-run[data-run-id="A"] .editor-run-hit-area').click({force:true});
  await f.getByLabel('Cajas sueltas sobre repisa',{exact:true}).check();
  await expect(f.getByLabel('Cajas sueltas sobre repisa',{exact:true})).toBeChecked();
  await f.getByRole('button',{name:'3D directo',exact:true}).click();
  await expect(f.locator('canvas').first()).toBeVisible();
  await expect.poll(async()=>f.locator('canvas').first().evaluate(c=>c.toDataURL().length)).toBeGreaterThan(10000);
  await page.screenshot({path:path.join(evidence,'03-diseno-integrado.png')});
  await page.getByRole('button',{name:'Cerrar',exact:true}).click();
  await expect(page.locator('table tbody tr')).toHaveCount(2);
  await page.screenshot({path:path.join(evidence,'04-cotizacion-con-vistas.png'),fullPage:true});
  const pdfResponse=page.waitForResponse(r=>r.url().endsWith('/generate-quote') && r.request().method()==='POST',{timeout:60000});
  const saveResponse=page.waitForResponse(r=>r.url().endsWith('/save-quote') && r.request().method()==='POST',{timeout:60000});
  await page.getByRole('button',{name:'Generar Cotizacion PDF'}).click();
  const response=await pdfResponse;
  writeFileSync('output/request-e2e.json',response.request().postData());
  if(!response.ok()) throw new Error(await response.text());
  await expect(page.getByRole('button',{name:/Descargar/})).toBeVisible();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:/Descargar/}).click();
  const download=await downloadPromise;
  await download.saveAs('output/quote-e2e.pdf');
  const {readFileSync}=await import('node:fs');
  const bytes=readFileSync('output/quote-e2e.pdf');expect(bytes.subarray(0,4).toString()).toBe('%PDF');
  await page.screenshot({path:path.join(evidence,'05-pdf-generado.png'),fullPage:true});
  await page.setViewportSize({width:430,height:932});
  await expect(page.getByText('No se pudo leer la planilla de precios.',{exact:false})).toHaveCount(0);
  await expect.poll(async()=>page.frameLocator('iframe[title="Vista 3D de la cotizacion"]').locator('canvas').first().evaluate(c=>c.toDataURL().length)).toBeGreaterThan(10000);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(430);
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('dm_cotizador_state')).project3d.shelving.runs.length)).toBe(2);
  await page.screenshot({path:path.join(evidence,'06-cotizador-movil.png'),fullPage:true});
  expect((await saveResponse).ok()).toBe(true);
  const saved=await page.request.get(base+'/.netlify/functions/get-quotes',{headers:{'x-admin-password':'2003'}});
  const quote=(await saved.json()).quotes.find(q=>q.nombre==='CLIENTE DE PRUEBA');
  expect(quote).toBeTruthy();
  expect(quote.pdfUrl).toContain('/.netlify/functions/local-pdf?id=');
  const storedPdf=await page.request.get(quote.pdfUrl);
  expect((await storedPdf.body()).subarray(0,4).toString()).toBe('%PDF');
  expect(errors).toEqual([]);
  console.log(JSON.stringify({ok:true,pdfBytes:bytes.length,evidence}));
} finally {await browser.close();}
